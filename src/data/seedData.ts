// Generate relative dates for seed activities
const getRelativeDate = (hoursFromNow: number): string => {
  const d = new Date();
  d.setMinutes(0, 0, 0);
  d.setTime(d.getTime() + hoursFromNow * 60 * 60 * 1000);
  return d.toISOString();
};

